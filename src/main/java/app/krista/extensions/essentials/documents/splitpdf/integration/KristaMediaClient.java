package app.krista.extensions.essentials.documents.splitpdf.integration;

import app.krista.ksdk.files.FileHandle;
import app.krista.ksdk.files.FileRepository;
import org.jvnet.hk2.annotations.Service;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import javax.inject.Inject;
import java.io.BufferedOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Bridge between raw bytes and Krista's {@link app.krista.model.base.File} media reference.
 *
 * <p>{@code toJavaFile} pulls the uploaded PDF down so PDFBox can read it; {@code uploadBytes} pushes
 * each generated chunk back into the media store so the request can return it as a file output.</p>
 *
 * <p>Faithful to the outlook-4 / ServiceTrade idiom, with one hardening: temporary files are written
 * into a per-call temp directory rather than a fixed {@code /tmp/<name>} path, so two concurrent
 * splits of same-named documents cannot overwrite each other's bytes. File contents are never
 * logged — file names and media ids at DEBUG only.</p>
 */
@Service
public class KristaMediaClient {

    private static final Logger LOG = LoggerFactory.getLogger(KristaMediaClient.class);
    private static final String TMP_PREFIX = "split-pdf-";
    private static final int BUF = 8192;

    @Inject
    private FileRepository fileRepository;

    /** Krista File INPUT → local java.io.File, so its bytes can be read by the PDF engine. */
    public File toJavaFile(app.krista.model.base.File kfile) throws IOException {
        if (kfile == null) {
            throw new IllegalArgumentException("PDF File is required. Upload a PDF document to split.");
        }
        try (FileHandle handle = fileRepository.getFile(kfile)) {
            if (handle == null) {
                throw new IOException("Null file handle for: " + kfile.getFileName());
            }
            Path dir = Files.createTempDirectory(TMP_PREFIX);
            File out = dir.resolve(safeName(kfile.getFileName())).toFile();
            try (OutputStream os = new BufferedOutputStream(new FileOutputStream(out));
                 InputStream in = handle.getContent()) {
                byte[] buffer = new byte[BUF];
                int read;
                while ((read = in.read(buffer)) != -1) {
                    os.write(buffer, 0, read);
                }
            }
            LOG.debug("Downloaded Krista file {} for processing", out.getName());
            return out;
        } catch (IOException e) {
            throw e;
        } catch (Exception e) {
            throw new IOException("Failed to read Krista file: " + e.getMessage(), e);
        }
    }

    /**
     * Generated bytes → Krista File OUTPUT.
     *
     * @param content  the generated document's bytes
     * @param fileName the name the file should carry in Krista (sanitized before upload)
     */
    public app.krista.model.base.File uploadBytes(byte[] content, String fileName) throws IOException {
        if (content == null || content.length == 0) {
            throw new IOException("Refusing to upload an empty file: " + fileName);
        }
        try (FileHandle handle = fileRepository.createNewFileByName(safeName(fileName))) {
            if (handle == null) {
                throw new IOException("Null file handle for: " + fileName);
            }
            handle.setContent(new java.io.ByteArrayInputStream(content));
            app.krista.model.base.File result = handle.getFile();
            if (result == null) {
                throw new IOException("Null Krista File after upload: " + fileName);
            }
            LOG.debug("Uploaded {} ({} bytes) -> mediaId {}", result.getFileName(), content.length,
                    result.getMediaId());
            return result;
        } catch (IOException e) {
            throw e;
        } catch (Exception e) {
            throw new IOException("Failed to store Krista file: " + e.getMessage(), e);
        }
    }

    /** local java.io.File → Krista File OUTPUT (name sanitized). */
    public app.krista.model.base.File toKristaFile(File file) throws IOException {
        try (FileInputStream in = new FileInputStream(file)) {
            return uploadBytes(in.readAllBytes(), file.getName());
        }
    }

    /** Best-effort cleanup of a temp file and the per-call directory it lives in. */
    public void deleteQuietly(File file) {
        if (file == null) {
            return;
        }
        try {
            Files.deleteIfExists(file.toPath());
            File parent = file.getParentFile();
            if (parent != null && parent.getName().startsWith(TMP_PREFIX)) {
                Files.deleteIfExists(parent.toPath());
            }
        } catch (IOException e) {
            LOG.debug("Could not delete temporary file {}: {}", file.getName(), e.getMessage());
        }
    }

    private static String safeName(String name) {
        return name == null || name.isBlank() ? "file" : name.replaceAll("[^A-Za-z0-9._-]", "_");
    }
}
